/* Exclusivamente con Vite y backend conectados a una base QA local. */
const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'playwright')
const assert = require('node:assert/strict')
const fs = require('node:fs/promises')
const path = require('node:path')
const baseURL = process.env.POS_UI_URL || 'http://127.0.0.1:15199'
assert(/^http:\/\/(127\.0\.0\.1|localhost):/.test(baseURL), 'Usar Vite QA local')
assert(process.env.POS_TEST_PASSWORD, 'Define POS_TEST_PASSWORD')
const output = process.env.POS_VALIDATION_DIR || path.resolve(__dirname, '../../docs/validation/passwords')

async function main() {
  await fs.mkdir(output, { recursive: true })
  const browser = await chromium.launch({ channel: 'msedge', headless: true })
  const context = await browser.newContext({ baseURL, viewport: { width: 1440, height: 1000 } })
  const page = await context.newPage(), errors = [], loginRequests = [], createRequests = [], updateRequests = []
  page.on('pageerror', e => errors.push(e.message))
  page.on('request', request => {
    const pathname = new URL(request.url()).pathname
    if (request.method() === 'POST' && pathname === '/api/auth/login') loginRequests.push(request)
    if (request.method() === 'POST' && pathname === '/api/usuarios') createRequests.push(request)
    if (request.method() === 'PUT' && pathname.startsWith('/api/usuarios/')) updateRequests.push(request)
  })
  try {
    await page.goto('/')
    const password = page.getByLabel('Contraseña', { exact: true })
    await password.waitFor()
    assert.equal(await password.getAttribute('type'), 'password')
    assert.equal(await password.getAttribute('autocomplete'), 'current-password')
    await password.fill('  Prueba visual  ')
    await page.getByRole('button', { name: 'Mostrar contraseña', exact: true }).click()
    assert.equal(await password.getAttribute('type'), 'text')
    assert.equal(await password.inputValue(), '  Prueba visual  ')
    assert(await password.evaluate(input => document.activeElement === input))
    await page.getByRole('button', { name: 'Ocultar contraseña', exact: true }).click()
    await password.focus(); await page.keyboard.press('Tab'); await page.keyboard.press('Space')
    assert.equal(await password.getAttribute('type'), 'text')
    await page.keyboard.press('Space')
    assert.equal(await password.getAttribute('type'), 'password')
    assert.equal(loginRequests.length, 0, 'El ojito no debe iniciar sesión')
    await password.fill('')
    for (const width of [320, 390]) {
      await page.setViewportSize({ width, height: 844 })
      assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth))
    }
    await page.screenshot({ path: path.join(output, '01-login-movil.png'), fullPage: true, animations: 'disabled' })
    await page.setViewportSize({ width: 1440, height: 1000 })
    await page.getByLabel('Usuario', { exact: true }).fill('admin')
    await password.fill(process.env.POS_TEST_PASSWORD)
    let releaseLogin
    const loginGate = new Promise(resolve => { releaseLogin = resolve })
    await page.route('**/api/auth/login', async route => {
      const response = await route.fetch(); assert(response.ok())
      await loginGate; await route.fulfill({ response })
    })
    await Promise.all([page.waitForRequest(request => request.method() === 'POST' && new URL(request.url()).pathname === '/api/auth/login'), password.press('Enter')])
    await page.getByRole('button', { name: /Iniciando sesión/ }).waitFor()
    assert(await password.isDisabled()); assert(await page.locator('.password-toggle').isDisabled())
    await page.locator('.login-form form').evaluate(form => form.dispatchEvent(new Event('submit', { bubbles: true, cancelable: true })))
    assert.equal(loginRequests.length, 1)
    releaseLogin(); await page.locator('.sidebar').waitFor()
    await page.locator('.sidebar').getByRole('button', { name: 'Usuarios', exact: true }).click()
    await page.getByRole('button', { name: 'Nuevo usuario', exact: true }).click()
    let dialog = page.getByRole('dialog'), userPassword = dialog.getByLabel('Contraseña', { exact: true })
    assert.equal(await userPassword.inputValue(), '')
    assert.equal(await userPassword.getAttribute('type'), 'password')
    assert.equal(await userPassword.getAttribute('autocomplete'), 'new-password')
    assert(await dialog.evaluate(element => document.activeElement === element))
    const username = 'qa_eye_'+Date.now().toString().slice(-8)
    await dialog.getByLabel('Usuario', { exact: true }).fill(username)
    await dialog.getByLabel('Nombre Completo', { exact: true }).fill('Usuario QA visibilidad')
    await dialog.getByRole('checkbox', { name: 'MOZO', exact: true }).check()
    await userPassword.fill('á'.repeat(37))
    await dialog.getByRole('button', { name: 'Guardar', exact: true }).click()
    await dialog.getByRole('alert').getByText(/72 bytes UTF-8/).waitFor()
    assert.equal(createRequests.length, 0)
    const literalPassword = '  Ojo-UTF8#2026  '
    await userPassword.fill(literalPassword)
    await dialog.getByRole('button', { name: 'Mostrar contraseña', exact: true }).click()
    assert.equal(await userPassword.inputValue(), literalPassword)
    await dialog.getByRole('button', { name: 'Ocultar contraseña', exact: true }).click()
    await page.setViewportSize({ width: 390, height: 844 })
    assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth))
    assert(await dialog.evaluate(element => {
      const rect = element.getBoundingClientRect()
      return element.contains(document.elementFromPoint(rect.left + 10, rect.top + 10))
    }), 'La barra lateral no debe tapar el diálogo al cambiar a móvil')
    await dialog.getByRole('button', { name: 'Mostrar contraseña', exact: true }).click()
    await dialog.getByRole('button', { name: 'Ocultar contraseña', exact: true }).click()
    await dialog.screenshot({ path: path.join(output, '02-usuario-movil.png'), animations: 'disabled' })
    await page.setViewportSize({ width: 1440, height: 1000 })
    let releaseCreate
    const createGate = new Promise(resolve => { releaseCreate = resolve })
    await page.route('**/api/usuarios', async route => {
      if (route.request().method() !== 'POST') return route.continue()
      const response = await route.fetch(); assert.equal(response.status(), 201)
      await createGate; await route.fulfill({ response })
    })
    await Promise.all([page.waitForRequest(request => request.method() === 'POST' && new URL(request.url()).pathname === '/api/usuarios'), dialog.getByRole('button', { name: 'Guardar', exact: true }).click()])
    await dialog.getByRole('button', { name: /Guardando/ }).waitFor()
    assert(await dialog.getByRole('button', { name: 'Cerrar', exact: true }).isDisabled())
    assert(await dialog.locator('select[name="estado"]').isDisabled())
    assert(await dialog.getByRole('checkbox', { name: 'MOZO', exact: true }).isDisabled())
    await page.keyboard.press('Escape'); assert(await dialog.isVisible())
    await dialog.locator('form').evaluate(form => form.dispatchEvent(new Event('submit', { bubbles: true, cancelable: true })))
    assert.equal(createRequests.length, 1)
    assert.equal(createRequests[0].postDataJSON().contrasena, literalPassword)
    releaseCreate(); await dialog.waitFor({ state: 'hidden' })
    let row = page.getByRole('row').filter({ hasText: username })
    await row.waitFor()
    await row.getByRole('button', { name: 'Modificar usuario', exact: true }).click()
    dialog = page.getByRole('dialog'); userPassword = dialog.getByLabel('Contraseña', { exact: true })
    assert.equal(await userPassword.inputValue(), '')
    await dialog.getByText('Deja en blanco para conservar la contraseña actual.').waitFor()
    await page.keyboard.press('Shift+Tab')
    assert(await dialog.getByRole('button', { name: 'Guardar', exact: true }).evaluate(element => document.activeElement === element))
    await page.keyboard.press('Tab')
    assert(await dialog.getByRole('button', { name: 'Cerrar', exact: true }).evaluate(element => document.activeElement === element))
    await page.keyboard.press('Escape'); await dialog.waitFor({ state: 'hidden' })
    assert(await row.getByRole('button', { name: 'Modificar usuario', exact: true }).evaluate(element => document.activeElement === element))
    await row.getByRole('button', { name: 'Modificar usuario', exact: true }).click()
    dialog = page.getByRole('dialog')
    await dialog.getByLabel('Nombre Completo', { exact: true }).fill('Usuario QA editado sin cambiar contraseña')
    await dialog.getByRole('button', { name: 'Guardar', exact: true }).click()
    await dialog.waitFor({ state: 'hidden' })
    assert.equal(updateRequests.at(-1).postDataJSON().contrasena, '')
    const userContext = await browser.newContext({ baseURL })
    const userPage = await userContext.newPage(); userPage.on('pageerror', e => errors.push(e.message))
    await userPage.goto('/')
    await userPage.getByLabel('Usuario', { exact: true }).fill(username)
    await userPage.getByLabel('Contraseña', { exact: true }).fill(literalPassword)
    await userPage.getByRole('button', { name: 'Entrar', exact: true }).click()
    await userPage.locator('.sidebar').waitFor()
    await userContext.close()
    const users = await (await context.request.get('/api/usuarios')).json()
    assert(users.every(user => !('contrasena' in user)), 'Nunca enviar contraseñas al formulario de edición')
    const created = users.find(user => user.usuario === username)
    assert(created)
    let releaseDelete, observeDelete, deleteCount = 0
    const deleteGate = new Promise(resolve => { releaseDelete = resolve })
    const deleteStarted = new Promise(resolve => { observeDelete = resolve })
    await page.route(`**/api/usuarios/${created.id}`, async route => {
      if (route.request().method() !== 'DELETE') return route.continue()
      deleteCount++
      observeDelete()
      const response = await route.fetch(); assert.equal(response.status(), 204)
      await deleteGate; await route.fulfill({ response })
    })
    page.on('dialog', confirmation => confirmation.accept())
    row = page.getByRole('row').filter({ hasText: username })
    await row.getByRole('button', { name: 'Eliminar usuario', exact: true }).click()
    await deleteStarted
    await row.getByRole('button', { name: 'Eliminar usuario', exact: true }).evaluate(element => element.click())
    assert(await row.getByRole('button', { name: 'Modificar usuario', exact: true }).isDisabled())
    assert.equal(deleteCount, 1)
    releaseDelete(); await row.waitFor({ state: 'hidden' })
    assert.deepEqual(errors, [])
    await fs.writeFile(path.join(output, 'resultado.json'), JSON.stringify({ passed: true, errors, viewports: [1440, 320, 390],
      checks: ['ojito en login y usuarios sin enviar formularios', 'teclado y foco', 'login único bajo latencia', '72 bytes UTF-8', 'contraseña literal con espacios', 'creación única y campos bloqueados', 'editar con contraseña vacía conserva credencial', 'eliminación única', 'móvil sin desborde y diálogo encima de la barra lateral'] }, null, 2))
    console.log('PASS login y formularios: visibilidad, accesibilidad, autenticación, validaciones y envíos únicos.')
  } finally { await browser.close() }
}
main().catch(error => { console.error(error); process.exitCode = 1 })
